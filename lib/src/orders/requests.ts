import type { infer as zinfer } from "zod";
import { object, record, strictObject } from "zod";

import { Id, NonnegativeInt, PaginationQuery, PositiveInt } from "../common";
import { OrderStatusSchema, ShippingMethodSchema } from "./types";

export const CreateOrderBody = strictObject({
  id: Id.meta({ description: "Generated by the client so a retried request can't place the same order twice." }),
  addressId: Id,
  paymentMethodId: Id,
  shippingMethod: ShippingMethodSchema,
  items: record(Id, PositiveInt).meta({
    description: "The cart the customer reviewed. The order fails if the stored cart no longer matches."
  }),
  expectedTotal: NonnegativeInt.meta({
    description: "The total the customer reviewed. The order fails if prices changed since then."
  })
});
export type CreateOrderBody = zinfer<typeof CreateOrderBody>;

export const UpdateOrderStatusBody = strictObject({
  status: OrderStatusSchema
});
export type UpdateOrderStatusBody = zinfer<typeof UpdateOrderStatusBody>;

export const ListOrdersQuery = object({
  ...PaginationQuery.shape,
  customerId: Id.optional(),
  status: OrderStatusSchema.optional()
});
export type ListOrdersQuery = zinfer<typeof ListOrdersQuery>;
